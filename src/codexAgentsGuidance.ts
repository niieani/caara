/** Returns the marker opening the Caara-managed block inside the global Codex AGENTS.md. */
export const codexAgentsGuidanceBeginMarker = (): string => "<!-- caara:agents:begin -->";

/** Returns the marker closing the Caara-managed block inside the global Codex AGENTS.md. */
export const codexAgentsGuidanceEndMarker = (): string => "<!-- caara:agents:end -->";

/** Options selecting the rendered guidance content. */
export interface RenderCodexAgentsGuidanceBlockOptions {
  readonly panelSkillInstalled: boolean;
}

/** Result of computing the next guidance document content. */
export type CodexAgentsGuidanceUpdate =
  | {
      readonly _tag: "Write";
      readonly content: string;
    }
  | {
      readonly _tag: "Delete";
    }
  | {
      readonly _tag: "Unchanged";
    }
  | {
      readonly _tag: "Corrupt";
      readonly reason: string;
    };

